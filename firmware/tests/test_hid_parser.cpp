TEST(extract_bits_unaligned) {
  const uint8_t d[] = {0xAB, 0xCD, 0xEF, 0x12};
  CHECK_EQ(extractBits(d, 4, 0, 8), 0xAB);
  CHECK_EQ(extractBits(d, 4, 4, 8), 0xDA);
  CHECK_EQ(extractBits(d, 4, 4, 12), 0xCDA);
  CHECK_EQ(extractBits(d, 4, 12, 12), 0xEFC);
  CHECK_EQ(extractBits(d, 4, 0, 32), 0x12EFCDAB);
  CHECK_EQ(extractBits(d, 4, 28, 8), 0x01);   // past the end reads as zero
}

TEST(boot_keyboard_tinyusb) {
  Layout l;
  CHECK(parse(kTinyUsbKbd, sizeof kTinyUsbKbd, l));
  CHECK(!l.has_report_ids);
  CHECK(l.hasKeyboard());
  CHECK(!l.hasMouse());
  CHECK(l.has_leds);
  CHECK_EQ(l.led_bit_off, 0);
  CHECK_EQ(l.led_first, 1);
  CHECK_EQ(l.led_count, 5);
  CHECK_EQ(l.led_report_bytes, 1);

  const uint8_t r[8] = {0x02 /*LShift*/, 0, 0x04 /*a*/, 0x05 /*b*/, 0, 0, 0, 0};
  Decoded d;
  decode(l, r, 8, d);
  CHECK(d.what & Decoded::KBD);
  CHECK_EQ(d.mods, 0x02);
  CHECK(d.key(0x04));
  CHECK(d.key(0x05));
  CHECK(!d.key(0x06));
  CHECK(!d.rollover);
}

TEST(keyboard_rollover_and_sign_quirk) {
  Layout l;
  CHECK(parse(kKbdSignQuirk, sizeof kKbdSignQuirk, l));
  // the array must accept 0xE3 (> 127) despite "Logical Maximum (-1)"
  const uint8_t r[8] = {0, 0, 0xE3, 0x2C, 0, 0, 0, 0};
  Decoded d;
  decode(l, r, 8, d);
  CHECK_EQ(d.mods, 0x08);   // usage 0xE3 (LGui) in the array -> modifier bit 3
  CHECK(d.key(0x2C));
  const uint8_t ro[8] = {0, 0, 1, 1, 1, 1, 1, 1};
  decode(l, ro, 8, d);
  CHECK(d.rollover);
}

TEST(boot_keyboard_fallback_matches_descriptor) {
  Layout a, b;
  parse(kTinyUsbKbd, sizeof kTinyUsbKbd, a);
  bootKeyboard(b);
  const uint8_t r[8] = {0x11, 0, 0x29, 0x3a, 0x04, 0, 0, 0};
  Decoded da, db;
  decode(a, r, 8, da);
  decode(b, r, 8, db);
  CHECK_EQ(da.mods, db.mods);
  CHECK(memcmp(da.keys, db.keys, sizeof da.keys) == 0);
}

TEST(mouse_16bit_reportid) {
  Layout l;
  CHECK(parse(kMouse16, sizeof kMouse16, l));
  CHECK(l.has_report_ids);
  CHECK(l.hasMouse());
  CHECK(!l.hasKeyboard());
  // rid 2 | buttons 16 bits | x16 | y16 | wheel | pan
  const uint8_t r[] = {0x02, 0x05, 0x80, 0x34, 0x12, 0x00, 0xF0, 0xFF, 0x7F};
  Decoded d;
  decode(l, r, sizeof r, d);
  CHECK(d.what & Decoded::MOUSE);
  CHECK_EQ(d.buttons, 0x8005);
  CHECK_EQ(d.x, 0x1234);
  CHECK_EQ(d.y, -4096);
  CHECK_EQ(d.wheel, -1);
  CHECK_EQ(d.pan, 127);
  // other report IDs (e.g. HID++ 0x10) decode to nothing
  const uint8_t hidpp[] = {0x10, 0xff, 0x00, 0x00, 0x00, 0x00, 0x00};
  decode(l, hidpp, sizeof hidpp, d);
  CHECK_EQ(d.what, 0);
}

TEST(mouse_12bit_packed) {
  Layout l;
  CHECK(parse(kMouse12, sizeof kMouse12, l));
  // x = -2 (0xFFE), y = +300 (0x12C): bytes after buttons: x lo8, (y lo4 << 4 | x hi4), y hi8
  const uint8_t r[] = {0x02, 0x01, 0x00, 0xFE, 0xCF, 0x12, 0x01};
  Decoded d;
  decode(l, r, sizeof r, d);
  CHECK_EQ(d.buttons, 0x0001);
  CHECK_EQ(d.x, -2);
  CHECK_EQ(d.y, 300);
  CHECK_EQ(d.wheel, 1);
}

TEST(mouse_8bit_and_boot_fallback) {
  Layout l, b;
  CHECK(parse(kMouse8, sizeof kMouse8, l));
  bootMouse(b);
  const uint8_t r[] = {0x03, 0x85, 0x10, 0xFF};
  Decoded d1, d2;
  decode(l, r, 4, d1);
  decode(b, r, 4, d2);
  CHECK_EQ(d1.buttons, 3);
  CHECK_EQ(d1.x, -123);
  CHECK_EQ(d1.y, 16);
  CHECK_EQ(d1.wheel, -1);
  CHECK_EQ(d2.buttons, d1.buttons);
  CHECK_EQ(d2.x, d1.x);
  CHECK_EQ(d2.y, d1.y);
  CHECK_EQ(d2.wheel, d1.wheel);
  // 3-byte boot report (no wheel byte)
  decode(b, r, 3, d2);
  CHECK_EQ(d2.wheel, 0);
}

TEST(mouse_absolute_xy_ignored) {
  // Same as kMouse8 but Input(Data,Var,Abs) 0x02: absolute pointer (tablet) -> not mouse motion.
  uint8_t desc[sizeof kMouse8];
  memcpy(desc, kMouse8, sizeof desc);
  desc[sizeof desc - 3] = 0x02;
  Layout l;
  parse(desc, sizeof desc, l);
  const uint8_t r[] = {0x00, 0x10, 0x10, 0x00};
  Decoded d;
  decode(l, r, 4, d);
  CHECK_EQ(d.x, 0);
  CHECK_EQ(d.y, 0);
}

TEST(nkro_bitmap_leds_and_consumer) {
  Layout l;
  CHECK(parse(kNkro, sizeof kNkro, l));
  CHECK(l.has_report_ids);
  CHECK(l.hasKeyboard());
  CHECK(l.hasConsumer());
  CHECK(l.has_leds);
  CHECK_EQ(l.led_rid, 1);
  CHECK_EQ(l.led_bit_off, 0);
  CHECK_EQ(l.led_report_bytes, 1);

  // rid 1: mods, then bitmap: usage u is bit u of the 120-bit field
  uint8_t r[1 + 1 + 15] = {0x01, 0x01 /*LCtrl*/};
  auto press = [&](uint8_t u) { r[2 + u / 8] |= 1 << (u % 8); };
  press(0x04); press(0x05); press(0x06); press(0x07); press(0x08); press(0x09); press(0x0A); press(0x2C);
  Decoded d;
  decode(l, r, sizeof r, d);
  CHECK_EQ(d.what, Decoded::KBD);
  CHECK_EQ(d.mods, 0x01);
  int n = 0;
  for (int u = 0; u < 256; ++u) n += d.key((uint8_t)u);
  CHECK_EQ(n, 8);   // 8 keys at once: more than 6KRO

  const uint8_t c[] = {0x02, 0xE9, 0x00};
  decode(l, c, sizeof c, d);
  CHECK_EQ(d.what, Decoded::CONS);
  CHECK_EQ(d.cons, 0xE9);
}

TEST(consumer_bits) {
  Layout l;
  CHECK(parse(kConsBits, sizeof kConsBits, l));
  const uint8_t r[] = {0x03, 0x02};   // second bit = Volume Down
  Decoded d;
  decode(l, r, sizeof r, d);
  CHECK_EQ(d.cons, 0xEA);
  const uint8_t z[] = {0x03, 0x00};
  decode(l, z, sizeof z, d);
  CHECK(d.what & Decoded::CONS);
  CHECK_EQ(d.cons, 0);
}

TEST(own_output_descriptor_roundtrip) {
  Layout l;
  CHECK(parse(kOurMouse, sizeof kOurMouse, l));
  MouseReport m{0x15, -32767, 12345, -128 + 1, 7};
  uint8_t r[1 + sizeof m] = {RID_MOUSE};
  memcpy(r + 1, &m, sizeof m);
  Decoded d;
  decode(l, r, sizeof r, d);
  CHECK_EQ(d.buttons, 0x15);
  CHECK_EQ(d.x, -32767);
  CHECK_EQ(d.y, 12345);
  CHECK_EQ(d.wheel, -127);
  CHECK_EQ(d.pan, 7);
  const uint8_t c[] = {RID_CONSUMER, 0xE9, 0x00};
  decode(l, c, sizeof c, d);
  CHECK_EQ(d.cons, 0xE9);
}

TEST(malformed_descriptor_is_safe) {
  const uint8_t bad[] = {0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x26, 0xff};   // truncated 2-byte item
  Layout l;
  CHECK(!parse(bad, sizeof bad, l));
  CHECK(!parse(nullptr, 0, l));
  // 70 separate X fields: must stop at kMaxFields and flag truncation, not overflow
  uint8_t big[16 + 70 * 2 + 8];
  int k = 0;
  const uint8_t head[] = {0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x75, 0x08, 0x95, 0x46, 0x15, 0x81, 0x25, 0x7f};
  memcpy(big, head, sizeof head);
  k = sizeof head;
  for (int i = 0; i < 70; ++i) { big[k++] = 0x09; big[k++] = 0x30; }
  big[k++] = 0x81; big[k++] = 0x06; big[k++] = 0xc0;
  CHECK(parse(big, (uint16_t)k, l));
  CHECK(l.truncated);
  CHECK_EQ(l.n, kMaxFields);
}
